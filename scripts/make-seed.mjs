// Writes supabase/seed.sql from the example venues in index.html, so the database starts
// with the same venues, rooms, extras, good-to-know details and reviews as the demo.
// Every row is marked is_demo = true, so it can all be removed before launch:
//   delete from public.venues where is_demo;
import { readFileSync, writeFileSync } from "node:fs";

const SRC = readFileSync("index.html", "utf8");
function literal(name) {
  const start = SRC.search(new RegExp(`const ${name}\\s*=\\s*[\\[{]`));
  if (start < 0) throw new Error(`Couldn't find ${name} in index.html`);
  let i = SRC.indexOf("=", start) + 1;
  while (/\s/.test(SRC[i])) i++;
  const from = i; let depth = 0, quote = null;
  for (; i < SRC.length; i++) {
    const c = SRC[i];
    if (quote) { if (c === "\\") i++; else if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "[" || c === "{") depth++;
    else if ((c === "]" || c === "}") && --depth === 0) break;
  }
  return Function(`return ${SRC.slice(from, i + 1)}`)();
}
const VENUES = literal("VENUES"), LOC = literal("LOC"), FLAGS = literal("FLAGS"), VINFO = literal("VINFO");
const ROOMS = literal("ROOMS"), REVIEWS = literal("REVIEWS"), POLICY_OF = literal("POLICY_OF");

const q = (v) => v == null ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const arr = (a) => a && a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]";
const pence = (pounds) => Math.round(pounds * 100);
const slugOf = (v) => v.name.toLowerCase().replace(/&/g, "and").replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const MONTHS = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };

const out = ["-- Example venues from the Vendo demo. Generated by scripts/make-seed.mjs; do not edit by hand.",
  "-- Remove before launch with: delete from public.venues where is_demo;", "begin;", "delete from public.venues where is_demo;", ""];

for (const v of VENUES) {
  const [lat, lng] = LOC[v.id] || [null, null], f = FLAGS[v.id] || {}, g = VINFO[v.id] || {};
  out.push(`with v as (insert into public.venues (slug, status, is_demo, name, kind, venue_type, place, region, lat, lng, space_title, blurb, suits, features, house_rules, instant_book, reply_note, step_free, licensed_bar, outdoor_space, cancellation_policy, finish_time, music_note, parking, getting_there, own_cake_decor, if_it_rains)
  values (${[q(slugOf(v)), "'live'", "true", q(v.name), q(v.kind), q(v.type), q(v.place), q(v.region), q(lat), q(lng), q(v.space), q(v.blurb),
    arr(v.suits), arr(v.features), arr(v.rules), q(!!v.instant), q(v.reply), q(!!f.stepfree), q(!!f.bar), q(!!f.outdoor),
    q(POLICY_OF[v.id] || "moderate"), q(g.finish), q(g.music), q(g.park), q(g.go), q(g.own), q(g.rain)].join(", ")}) returning id)`);
  const rooms = ROOMS[v.id] || [{ name: v.space, seated: v.seated, standing: v.standing, hour: v.hour, day: v.day, minH: v.minH, note: null }];
  const listed = v.id === "plough" ? [true, true, false] : rooms.map(() => true);
  const roomRows = rooms.map((r, i) => `((select id from v), ${q(r.name)}, ${q(r.note || null)}, ${r.seated}, ${r.standing}, ${pence(r.hour)}, ${pence(r.day)}, ${r.minH}, ${listed[i]}, ${i})`);
  const addonRows = v.addons.map((a, i) => `((select id from v), ${q(a.l)}, ${pence(a.p)}, ${!!a.head}, ${i})`);
  const reviewRows = (REVIEWS[v.id] || []).map(([name, ev, when, stars, text, reply]) => {
    const [mon, yr] = when.split(" ");
    return `((select id from v), ${q(name)}, ${q(ev)}, ${stars}, ${q(text)}, ${q(reply || null)}, '${yr}-${String(MONTHS[mon]).padStart(2, "0")}-15')`;
  });
  out.push(`, r as (insert into public.rooms (venue_id, name, note, seated, standing, hour_price_pence, day_price_pence, min_hours, is_listed, sort_order) values\n  ${roomRows.join(",\n  ")} returning 1)`);
  out.push(`, a as (insert into public.addons (venue_id, label, price_pence, per_head, sort_order) values\n  ${addonRows.join(",\n  ")} returning 1)`);
  out.push(reviewRows.length
    ? `insert into public.venue_reviews (venue_id, author_name, event_label, stars, body, host_reply, created_at) values\n  ${reviewRows.join(",\n  ")};\n`
    : "select 1;\n");
}
out.push("commit;", "");
writeFileSync("supabase/seed.sql", out.join("\n"));
console.log(`Wrote supabase/seed.sql: ${VENUES.length} venues, ${VENUES.reduce((n, v) => n + (ROOMS[v.id] || [1]).length, 0)} rooms, ${VENUES.reduce((n, v) => n + v.addons.length, 0)} extras, ${Object.values(REVIEWS).flat().length} reviews.`);
